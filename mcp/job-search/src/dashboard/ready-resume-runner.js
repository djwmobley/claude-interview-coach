// @ts-check
/**
 * Listing-mode resume runner for the Ready to apply list (spec 9.3, R4, A5, A10). Same headless `claude`
 * shape as src/dashboard/resume-runner.js and review-runner.js (detached spawn, hard-timeout taskkill
 * backstop, child never unref'd) but scoped to a LISTING, never an application: it never reads or writes
 * ic_job_applications.
 *
 * generate(listingId, runId): /write-resume with `<listingId> headless:listing run:<runId>`. The skill
 * writes its markdown under output/markdown/ready/<runId>/ (a directory only this run uses) and renders
 * the DOCX through render_doc with listingId only. Success is decided by disk and database state only:
 *   - a .md file exists in output/markdown/ready/<runId>/ (ties the result to THIS run, never "newest
 *     file"), AND
 *   - an ic_job_documents row with kind 'resume' and THIS listing_id was created during the run, or its
 *     file was (re)written during the run, and that file exists under the output root.
 * Failure reasons, in precedence: no_description (precheck, no spawn, refund) | spawn_failed (refund) |
 * timeout | <HEADLESS_ABORT reason> | model_asked | markdown_not_found | no_document.
 *
 * review(listingId, markdownPath): the existing advisory /review-cv run (R4), parsed with
 * review-runner.js's parseReviewResult. Never decides anything by itself; the caller stores the verdict.
 *
 * The caller holds the shared cross-process spawn lock (src/core/resume-spawn-lock.js) around both calls.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { errFields } from '../core/errors.js';
import { log as defaultLog } from '../core/logger.js';
import { DETAIL_MIN_CHARS } from '../core/normalize.js';
import { parseReviewResult } from './review-runner.js';
import { buildClaudeArgs, buildChildEnv, SPAWN_PROFILES } from '../core/claude-spawn.js';
import { checkResumeFile } from '../core/resume-leak-gate.js';

const HEADLESS_ABORT_RE = /HEADLESS_ABORT:\s*([a-z0-9_]+)/i;
const QUESTION_SHAPED_RE = /\b(want me to|should i|shall i|do you want|would you like|can i confirm|proceed anyway|is (?:it|that) ok(?:ay)? if)\b/i;
/** Run ids are generated by the caller; anything else is refused before it reaches a path or a prompt. */
const RUN_ID_RE = /^[a-z0-9][a-z0-9-]{2,63}$/;

/**
 * @param {{
 *   env: any, logDir: string, repoRoot: string, withClient: <T>(fn: (c: import('pg').ClientBase) => Promise<T>) => Promise<T>,
 *   spawn: typeof import('node:child_process').spawn, execFile?: typeof execFile,
 *   claudeBin?: string, model?: string, reviewModel?: string, maxTurns?: number, budgetUsd?: number, timeoutMs?: number,
 *   log?: (f: Record<string, unknown>) => void, profilePath?: string,
 * }} deps
 */
export function createReadyResumeRunner(deps) {
  const say = deps.log ?? ((f) => defaultLog.info(/** @type {any} */ (f)));
  const doExecFile = deps.execFile ?? execFile;
  const claudeBin = deps.claudeBin ?? deps.env.JOBSEARCH_CLAUDE_BIN;
  const model = deps.model ?? deps.env.JOBSEARCH_RESUME_MODEL;
  const reviewModel = deps.reviewModel ?? deps.env.JOBSEARCH_REVIEW_MODEL;
  const maxTurns = deps.maxTurns ?? deps.env.JOBSEARCH_RESUME_MAX_TURNS;
  const budgetUsd = deps.budgetUsd ?? deps.env.JOBSEARCH_RESUME_BUDGET_USD;
  const timeoutMs = deps.timeoutMs ?? deps.env.JOBSEARCH_RESUME_TIMEOUT_MS;
  const outputRoot = path.join(deps.repoRoot, 'output');

  /**
   * @param {string} prompt
   * @param {string} useModel
   * @param {string} tag
   * @param {import('../core/claude-spawn.js').SpawnProfile} profile
   * @returns {Promise<{ timedOut: boolean, spawnError: boolean, exitCode: number|null, resultText: string, wrapperOk: boolean }>}
   */
  async function spawnHeadless(prompt, useModel, tag, profile) {
    fs.mkdirSync(deps.logDir, { recursive: true });
    const mcpConfigPath = path.join(deps.logDir, `${tag}-mcp-${Date.now()}.json`);
    fs.copyFileSync(path.join(deps.repoRoot, '.mcp.json'), mcpConfigPath);
    // Least privilege (src/core/claude-spawn.js): dontAsk, the skill's tool set only, allowlisted env.
    const argv = buildClaudeArgs({ prompt, model: useModel, profile, maxTurns, budgetUsd, mcpConfigPath });
    const spawnEnv = buildChildEnv(process.env, deps.env);
    /** @type {any} */
    let child;
    try {
      child = deps.spawn(claudeBin, argv, { cwd: deps.repoRoot, detached: true, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true, env: spawnEnv });
    } catch (err) {
      say({ evt: `${tag}_spawn_error`, err_message: errFields(err).err_message });
      return { timedOut: false, spawnError: true, exitCode: null, resultText: '', wrapperOk: false };
    }
    let stdout = '';
    child.stdout?.on('data', (/** @type {Buffer} */ chunk) => { stdout = (stdout + chunk.toString('utf8')).slice(-2_000_000); });
    child.stderr?.on('data', () => {});
    /** @type {{ timedOut: boolean, exitCode: number|null, spawnError: boolean }} */
    const outcome = await new Promise((resolve) => {
      let settled = false;
      const finish = (/** @type {any} */ v) => { if (!settled) { settled = true; resolve(v); } };
      // Left ref'd on purpose (see resume-runner.js): the timer and the child keep the event loop alive.
      const hardTimer = setTimeout(() => {
        doExecFile('taskkill', ['/pid', String(child.pid), '/T', '/F'], () => {});
        finish({ timedOut: true, exitCode: null, spawnError: false });
      }, timeoutMs);
      child.on('exit', (/** @type {number|null} */ code) => { clearTimeout(hardTimer); finish({ timedOut: false, exitCode: code, spawnError: false }); });
      child.on('error', () => { clearTimeout(hardTimer); finish({ timedOut: false, exitCode: null, spawnError: true }); });
    });
    /** @type {any} */
    let json = null;
    try {
      json = JSON.parse(stdout);
    } catch {
      json = null;
    }
    const wrapperOk = Boolean(json && typeof json.result === 'string');
    return { ...outcome, resultText: wrapperOk ? json.result : stdout, wrapperOk };
  }

  /** @param {string} runId */
  function findRunMarkdown(runId) {
    const dir = path.join(outputRoot, 'markdown', 'ready', runId);
    let names = [];
    try {
      names = fs.readdirSync(dir).filter((n) => n.toLowerCase().endsWith('.md')).sort();
    } catch {
      return null;
    }
    return names.length ? `output/markdown/ready/${runId}/${names[0]}` : null;
  }

  /**
   * @param {number} listingId
   * @param {string} runId
   * @returns {Promise<{ ok: true, docId: number, relPath: string, markdownPath: string } | { ok: false, reason: string, refund?: boolean }>}
   */
  async function generate(listingId, runId) {
    if (!Number.isInteger(listingId) || listingId <= 0) return { ok: false, reason: 'invalid_listing', refund: true };
    if (!RUN_ID_RE.test(runId)) return { ok: false, reason: 'invalid_run_id', refund: true };
    const desc = await deps.withClient((c) => c.query('SELECT description FROM ic_job_listings WHERE id = $1', [listingId]));
    const description = desc.rowCount ? desc.rows[0].description : null;
    if (typeof description !== 'string' || description.length < DETAIL_MIN_CHARS) return { ok: false, reason: 'no_description', refund: true };

    const startedAt = new Date();
    say({ evt: 'ready_resume_started', listing_id: listingId, run_id: runId });
    const out = await spawnHeadless(`Run the /write-resume skill with argument ${listingId} headless:listing run:${runId}`, model, 'ready-resume', SPAWN_PROFILES['write-resume']);
    if (out.spawnError) return { ok: false, reason: 'spawn_failed', refund: true };
    if (out.timedOut) return { ok: false, reason: 'timeout' };

    const markdownPath = findRunMarkdown(runId);
    const docs = await deps.withClient((c) => c.query(
      `SELECT id, rel_path, created_at FROM ic_job_documents WHERE listing_id = $1 AND kind = 'resume' ORDER BY created_at DESC, id DESC`,
      [listingId],
    ));
    const cutoff = startedAt.getTime() - 2000;
    const fresh = docs.rows.find((d) => {
      const abs = path.join(outputRoot, ...String(d.rel_path).split('/'));
      let mtime = -1;
      try {
        mtime = fs.statSync(abs).mtimeMs;
      } catch {
        return false;
      }
      return new Date(d.created_at).getTime() >= cutoff || mtime >= cutoff;
    });
    if (markdownPath && fresh) {
      // Private-data gate (src/core/resume-leak-gate.js): block before review, ledger 'ready', or any submit.
      // The generated document row is deleted so findReusableResume can never hand it to a later run.
      const gate = checkResumeFile({ repoRoot: deps.repoRoot, markdownPath, profilePath: deps.profilePath });
      if (!gate.ok) {
        await deps.withClient((c) => c.query('DELETE FROM ic_job_documents WHERE id = $1', [Number(fresh.id)])).catch(() => {});
        say({ evt: 'ready_resume_private_data_blocked', listing_id: listingId, run_id: runId, reason: gate.reason, kind: gate.detail });
        return { ok: false, reason: gate.reason };
      }
      say({ evt: 'ready_resume_success', listing_id: listingId, run_id: runId, doc_id: Number(fresh.id) });
      return { ok: true, docId: Number(fresh.id), relPath: String(fresh.rel_path), markdownPath };
    }
    const abort = HEADLESS_ABORT_RE.exec(out.resultText);
    if (abort) return { ok: false, reason: abort[1].toLowerCase() };
    const t = out.resultText.trim();
    if (t && (t.endsWith('?') || QUESTION_SHAPED_RE.test(t))) return { ok: false, reason: 'model_asked' };
    if (!markdownPath) return { ok: false, reason: 'markdown_not_found' };
    return { ok: false, reason: 'no_document' };
  }

  /**
   * @param {number} listingId
   * @param {string} markdownPath repo-relative
   * @returns {Promise<{ ok: true, verdict: 'PASS'|'FAIL', findings: any } | { ok: false, reason: string }>}
   */
  async function review(listingId, markdownPath) {
    const out = await spawnHeadless(`Run the /review-cv skill with argument ${markdownPath} listing:${listingId}`, reviewModel, 'ready-review', SPAWN_PROFILES['review-cv']);
    if (out.spawnError) return { ok: false, reason: 'spawn_failed' };
    if (out.timedOut) return { ok: false, reason: 'timeout' };
    if (!out.wrapperOk) return { ok: false, reason: 'json_wrapper_unparseable' };
    const parsed = parseReviewResult(out.resultText);
    if (!parsed.ok) return { ok: false, reason: parsed.reason };
    return { ok: true, verdict: parsed.verdict, findings: parsed.findings };
  }

  return { generate, review };
}
